    ),
    CONSTRAINT fk_secuencia_restaurante
        FOREIGN KEY (restaurante_id) REFERENCES restaurantes(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT
);

CREATE TABLE facturas (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurante_id              BIGINT NOT NULL,
    cuenta_id                   BIGINT NOT NULL,
    subcuenta_id                BIGINT NULL,
    turno_caja_id               BIGINT NOT NULL,
    configuracion_id            BIGINT NOT NULL,
    cliente_id                  BIGINT NULL,
    mesero_id                   BIGINT NOT NULL,
    cajero_id                   BIGINT NOT NULL,
    tipo_documento              VARCHAR(20) NOT NULL DEFAULT 'COMPROBANTE',
    serie                       VARCHAR(20) NOT NULL,
    numero_correlativo          BIGINT NOT NULL,
    numero_documento            VARCHAR(50) NOT NULL,
    estado                      VARCHAR(15) NOT NULL DEFAULT 'EMITIDA',
    subtotal                    DECIMAL(12,2) NOT NULL,
    descuento_total             DECIMAL(12,2) NOT NULL DEFAULT 0,
    descuento_puntos            DECIMAL(12,2) NOT NULL DEFAULT 0,
    porcentaje_impuesto         DECIMAL(7,4) NOT NULL,
    monto_impuesto              DECIMAL(12,2) NOT NULL,
    porcentaje_propina          DECIMAL(7,4) NOT NULL,
    monto_propina               DECIMAL(12,2) NOT NULL,
    total                       DECIMAL(12,2) NOT NULL,
    puntos_redimidos            BIGINT NOT NULL DEFAULT 0,
    puntos_otorgados            BIGINT NOT NULL DEFAULT 0,
    emitida_en                  TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    anulada_en                  TIMESTAMPTZ(6) NULL,
    anulada_por_id              BIGINT NULL,
    motivo_anulacion            VARCHAR(500) NULL,
    CONSTRAINT uq_factura_documento
        UNIQUE (restaurante_id, tipo_documento, serie, numero_correlativo),
    CONSTRAINT uq_factura_numero_documento
        UNIQUE (restaurante_id, numero_documento),
    CONSTRAINT chk_factura_tipo CHECK (
        tipo_documento IN ('FACTURA', 'COMPROBANTE')
    ),
    CONSTRAINT chk_factura_identificacion CHECK (
        numero_correlativo > 0
        AND NULLIF(BTRIM(serie), '') IS NOT NULL
        AND NULLIF(BTRIM(numero_documento), '') IS NOT NULL
    ),
    CONSTRAINT chk_factura_estado CHECK (
        estado IN ('EMITIDA', 'ANULADA')
    ),
    CONSTRAINT chk_factura_montos CHECK (
        subtotal >= 0
        AND descuento_total >= 0
        AND descuento_total <= subtotal
        AND descuento_puntos >= 0
        AND descuento_puntos <= descuento_total
        AND porcentaje_impuesto BETWEEN 0 AND 100
        AND monto_impuesto >= 0
        AND porcentaje_propina BETWEEN 0 AND 100
        AND monto_propina >= 0
        AND total >= 0
        AND puntos_redimidos >= 0
        AND puntos_otorgados >= 0
        AND total = ROUND(
            subtotal - descuento_total + monto_impuesto + monto_propina,
            2
        )
    ),
    CONSTRAINT chk_factura_cliente_puntos CHECK (
        cliente_id IS NOT NULL
        OR (
            puntos_redimidos = 0
            AND puntos_otorgados = 0
            AND descuento_puntos = 0
        )
    ),
    CONSTRAINT chk_factura_anulacion CHECK (
        (estado = 'EMITIDA' AND anulada_en IS NULL)
        OR (estado = 'ANULADA' AND anulada_en IS NOT NULL AND motivo_anulacion IS NOT NULL)
    ),
    CONSTRAINT fk_factura_restaurante
        FOREIGN KEY (restaurante_id) REFERENCES restaurantes(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_factura_cuenta
        FOREIGN KEY (cuenta_id) REFERENCES cuentas(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_factura_subcuenta
        FOREIGN KEY (subcuenta_id) REFERENCES subcuentas(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_factura_turno
        FOREIGN KEY (turno_caja_id) REFERENCES turnos_caja(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_factura_configuracion
        FOREIGN KEY (configuracion_id) REFERENCES configuraciones_restaurante(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_factura_cliente
        FOREIGN KEY (cliente_id) REFERENCES clientes(id)
        ON UPDATE RESTRICT ON DELETE SET NULL,
    CONSTRAINT fk_factura_mesero
        FOREIGN KEY (mesero_id) REFERENCES usuarios(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_factura_cajero
        FOREIGN KEY (cajero_id) REFERENCES usuarios(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_factura_anulada_por
        FOREIGN KEY (anulada_por_id) REFERENCES usuarios(id)
        ON UPDATE RESTRICT ON DELETE SET NULL
);

CREATE UNIQUE INDEX uq_factura_cuenta_completa_emitida
