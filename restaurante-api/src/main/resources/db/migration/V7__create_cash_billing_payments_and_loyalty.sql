    activo              BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_metodo_pago_codigo UNIQUE (codigo),
    CONSTRAINT uq_metodo_pago_nombre UNIQUE (nombre)
);

CREATE TABLE secuencias_facturacion (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurante_id      BIGINT NOT NULL,
    tipo_documento      VARCHAR(20) NOT NULL DEFAULT 'COMPROBANTE',
    serie               VARCHAR(20) NOT NULL,
    ultimo_numero       BIGINT NOT NULL DEFAULT 0,
    activo              BOOLEAN NOT NULL DEFAULT TRUE,
    actualizado_en      TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_secuencia_documento
        UNIQUE (restaurante_id, tipo_documento, serie),
    CONSTRAINT chk_secuencia_tipo CHECK (
