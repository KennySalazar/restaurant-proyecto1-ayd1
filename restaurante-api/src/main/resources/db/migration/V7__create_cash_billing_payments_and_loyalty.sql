
SET search_path TO restaurante, public;
SET TIME ZONE 'UTC';

CREATE TABLE cajas (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurante_id  BIGINT NOT NULL,
    codigo          VARCHAR(30) NOT NULL,
    nombre          VARCHAR(100) NOT NULL,
    ubicacion       VARCHAR(150) NULL,
    activo          BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_caja_codigo UNIQUE (restaurante_id, codigo),
    CONSTRAINT uq_caja_nombre UNIQUE (restaurante_id, nombre),
    CONSTRAINT fk_caja_restaurante
        FOREIGN KEY (restaurante_id) REFERENCES restaurantes(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT
);

CREATE TABLE turnos_caja (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    caja_id                     BIGINT NOT NULL,
    cajero_id                   BIGINT NOT NULL,
    estado                      VARCHAR(10) NOT NULL DEFAULT 'ABIERTA',
    monto_inicial_efectivo      DECIMAL(12,2) NOT NULL,
    abierta_en                  TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    efectivo_esperado_cierre    DECIMAL(12,2) NULL,
    efectivo_real_cierre        DECIMAL(12,2) NULL,
    diferencia_cierre           DECIMAL(12,2) NULL,
    observaciones_apertura      VARCHAR(500) NULL,
    observaciones_cierre        VARCHAR(500) NULL,
    cerrada_en                  TIMESTAMPTZ(6) NULL,
    CONSTRAINT chk_turno_estado CHECK (estado IN ('ABIERTA', 'CERRADA')),
    CONSTRAINT chk_turno_montos CHECK (
        monto_inicial_efectivo >= 0
        AND (efectivo_esperado_cierre IS NULL OR efectivo_esperado_cierre >= 0)
        AND (efectivo_real_cierre IS NULL OR efectivo_real_cierre >= 0)
    ),
    CONSTRAINT chk_turno_cierre CHECK (
        (estado = 'ABIERTA'
            AND cerrada_en IS NULL
            AND efectivo_esperado_cierre IS NULL
            AND efectivo_real_cierre IS NULL
            AND diferencia_cierre IS NULL)
        OR (estado = 'CERRADA'
            AND cerrada_en IS NOT NULL
            AND efectivo_esperado_cierre IS NOT NULL
            AND efectivo_real_cierre IS NOT NULL
            AND diferencia_cierre = ROUND(
                efectivo_real_cierre - efectivo_esperado_cierre,
                2
            ))
    ),
    CONSTRAINT fk_turno_caja
        FOREIGN KEY (caja_id) REFERENCES cajas(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_turno_cajero
        FOREIGN KEY (cajero_id) REFERENCES usuarios(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT
);

CREATE UNIQUE INDEX uq_turno_caja_abierta
    ON turnos_caja (caja_id)
    WHERE estado = 'ABIERTA';

CREATE UNIQUE INDEX uq_turno_cajero_abierto
    ON turnos_caja (cajero_id)
    WHERE estado = 'ABIERTA';

CREATE INDEX idx_turnos_caja_historial
    ON turnos_caja (caja_id, abierta_en, cerrada_en);
CREATE INDEX idx_turnos_cajero_historial
    ON turnos_caja (cajero_id, abierta_en);

CREATE TABLE metodos_pago (
