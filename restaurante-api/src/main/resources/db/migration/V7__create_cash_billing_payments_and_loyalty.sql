    ON facturas (cliente_id, emitida_en);

CREATE TABLE factura_detalles (
    id                              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    factura_id                      BIGINT NOT NULL,
    comanda_detalle_id              BIGINT NOT NULL,
    platillo_id                     BIGINT NULL,
    combo_id                        BIGINT NULL,
    nombre_snapshot                 VARCHAR(150) NOT NULL,
    categoria_snapshot              VARCHAR(100) NULL,
    cantidad                        DECIMAL(12,6) NOT NULL,
    precio_unitario_snapshot        DECIMAL(12,2) NOT NULL,
    total_modificadores_snapshot    DECIMAL(12,2) NOT NULL DEFAULT 0,
    costo_unitario_snapshot         DECIMAL(14,4) NOT NULL DEFAULT 0,
    subtotal_linea                  DECIMAL(12,2) NOT NULL,
    CONSTRAINT uq_factura_comanda_detalle
        UNIQUE (factura_id, comanda_detalle_id),
    CONSTRAINT chk_factura_detalle_producto CHECK (
        (platillo_id IS NOT NULL AND combo_id IS NULL)
        OR (platillo_id IS NULL AND combo_id IS NOT NULL)
    ),
    CONSTRAINT chk_factura_detalle_valores CHECK (
        cantidad > 0
        AND precio_unitario_snapshot >= 0
        AND total_modificadores_snapshot >= 0
        AND costo_unitario_snapshot >= 0
        AND subtotal_linea = ROUND(
            cantidad * (
                precio_unitario_snapshot + total_modificadores_snapshot
            ),
            2
        )
    ),
    CONSTRAINT fk_factura_detalle_factura
        FOREIGN KEY (factura_id) REFERENCES facturas(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_factura_detalle_comanda
        FOREIGN KEY (comanda_detalle_id) REFERENCES comanda_detalles(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_factura_detalle_platillo
        FOREIGN KEY (platillo_id) REFERENCES platillos(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_factura_detalle_combo
        FOREIGN KEY (combo_id) REFERENCES combos(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT
);

CREATE INDEX idx_factura_detalles_reporte_producto
    ON factura_detalles (platillo_id, combo_id);

CREATE TABLE factura_detalle_modificadores (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    factura_detalle_id          BIGINT NOT NULL,
    modificador_id              BIGINT NULL,
    nombre_snapshot             VARCHAR(120) NOT NULL,
    cantidad                    SMALLINT NOT NULL DEFAULT 1,
    precio_adicional_snapshot   DECIMAL(12,2) NOT NULL DEFAULT 0,
    CONSTRAINT uq_factura_detalle_modificador
        UNIQUE (factura_detalle_id, modificador_id),
    CONSTRAINT chk_factura_modificador_valores CHECK (
        cantidad > 0 AND precio_adicional_snapshot >= 0
    ),
    CONSTRAINT fk_factura_mod_detalle
        FOREIGN KEY (factura_detalle_id) REFERENCES factura_detalles(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_factura_mod_modificador
        FOREIGN KEY (modificador_id) REFERENCES modificadores(id)
        ON UPDATE RESTRICT ON DELETE SET NULL
);

CREATE TABLE pagos (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    factura_id              BIGINT NOT NULL,
    metodo_pago_id          SMALLINT NOT NULL,
    monto                   DECIMAL(12,2) NOT NULL,
    monto_recibido          DECIMAL(12,2) NULL,
    cambio_entregado        DECIMAL(12,2) NULL,
    referencia             VARCHAR(120) NULL,
    autorizacion           VARCHAR(120) NULL,
    registrado_por_id      BIGINT NOT NULL,
    pagado_en               TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_pago_monto CHECK (
        monto > 0
        AND (monto_recibido IS NULL OR monto_recibido >= monto)
        AND (cambio_entregado IS NULL OR cambio_entregado >= 0)
        AND (
            monto_recibido IS NULL
            OR cambio_entregado = ROUND(monto_recibido - monto, 2)
        )
    ),
    CONSTRAINT fk_pago_factura
        FOREIGN KEY (factura_id) REFERENCES facturas(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_pago_metodo
        FOREIGN KEY (metodo_pago_id) REFERENCES metodos_pago(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_pago_usuario
        FOREIGN KEY (registrado_por_id) REFERENCES usuarios(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT
);

CREATE INDEX idx_pagos_factura
    ON pagos (factura_id, pagado_en);

CREATE TABLE transacciones_caja (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    turno_caja_id       BIGINT NOT NULL,
    factura_id          BIGINT NULL,
    pago_id             BIGINT NULL,
    tipo                VARCHAR(25) NOT NULL,
    monto               DECIMAL(12,2) NOT NULL DEFAULT 0,
    puntos              BIGINT NOT NULL DEFAULT 0,
    descripcion         VARCHAR(500) NOT NULL,
    registrada_por_id   BIGINT NOT NULL,
    registrada_en       TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_transaccion_caja_tipo CHECK (
        tipo IN (
            'APERTURA', 'VENTA', 'PROPINA', 'REDENCION_PUNTOS',
            'AJUSTE', 'CIERRE'
        )
    ),
    CONSTRAINT chk_transaccion_caja_monto CHECK (monto >= 0),
    CONSTRAINT chk_transaccion_caja_puntos CHECK (puntos >= 0),
    CONSTRAINT chk_transaccion_caja_origen CHECK (
        (tipo IN ('APERTURA', 'CIERRE')
            AND factura_id IS NULL AND pago_id IS NULL)
        OR (tipo = 'VENTA'
            AND factura_id IS NOT NULL AND pago_id IS NOT NULL)
        OR (tipo IN ('PROPINA', 'REDENCION_PUNTOS')
            AND factura_id IS NOT NULL AND pago_id IS NULL)
        OR (tipo = 'AJUSTE' AND pago_id IS NULL)
    ),
    CONSTRAINT fk_transaccion_turno
        FOREIGN KEY (turno_caja_id) REFERENCES turnos_caja(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_transaccion_factura
        FOREIGN KEY (factura_id) REFERENCES facturas(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_transaccion_pago
        FOREIGN KEY (pago_id) REFERENCES pagos(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_transaccion_usuario
        FOREIGN KEY (registrada_por_id) REFERENCES usuarios(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT
);

CREATE INDEX idx_transacciones_turno_fecha
    ON transacciones_caja (turno_caja_id, registrada_en);

CREATE UNIQUE INDEX uq_transaccion_caja_pago
    ON transacciones_caja (pago_id)
    WHERE pago_id IS NOT NULL;

CREATE UNIQUE INDEX uq_transaccion_caja_apertura
    ON transacciones_caja (turno_caja_id)
    WHERE tipo = 'APERTURA';

CREATE UNIQUE INDEX uq_transaccion_caja_cierre
    ON transacciones_caja (turno_caja_id)
    WHERE tipo = 'CIERRE';

CREATE UNIQUE INDEX uq_transaccion_caja_propina_factura
    ON transacciones_caja (factura_id)
    WHERE tipo = 'PROPINA';

CREATE UNIQUE INDEX uq_transaccion_caja_redencion_factura
    ON transacciones_caja (factura_id)
    WHERE tipo = 'REDENCION_PUNTOS';


CREATE TABLE movimientos_puntos (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id          BIGINT NOT NULL,
    factura_id          BIGINT NULL,
    tipo                VARCHAR(20) NOT NULL,
    cantidad_puntos     BIGINT NOT NULL,
    saldo_anterior      BIGINT NULL,
    saldo_resultante    BIGINT NULL,
    valor_monetario     DECIMAL(12,2) NOT NULL DEFAULT 0,
    motivo              VARCHAR(500) NOT NULL,
    registrado_por_id   BIGINT NULL,
    creado_en           TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_movimiento_puntos_factura_tipo UNIQUE (factura_id, tipo),
    CONSTRAINT chk_movimiento_puntos_tipo CHECK (
        tipo IN ('OTORGAMIENTO', 'REDENCION', 'AJUSTE')
    ),
    CONSTRAINT chk_movimiento_puntos_signo CHECK (
        (tipo = 'OTORGAMIENTO' AND cantidad_puntos > 0)
        OR (tipo = 'REDENCION' AND cantidad_puntos < 0)
        OR (tipo = 'AJUSTE' AND cantidad_puntos <> 0)
    ),
    CONSTRAINT chk_movimiento_puntos_saldos CHECK (
        (saldo_anterior IS NULL OR saldo_anterior >= 0)
        AND (saldo_resultante IS NULL OR saldo_resultante >= 0)
        AND valor_monetario >= 0
    ),
    CONSTRAINT fk_movimiento_puntos_cliente
        FOREIGN KEY (cliente_id) REFERENCES clientes(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_movimiento_puntos_factura
        FOREIGN KEY (factura_id) REFERENCES facturas(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_movimiento_puntos_usuario
        FOREIGN KEY (registrado_por_id) REFERENCES usuarios(id)
        ON UPDATE RESTRICT ON DELETE SET NULL
);

CREATE INDEX idx_movimientos_puntos_cliente_fecha
    ON movimientos_puntos (cliente_id, creado_en);
CREATE INDEX idx_movimientos_puntos_reporte
    ON movimientos_puntos (tipo, creado_en);

