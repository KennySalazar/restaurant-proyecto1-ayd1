CREATE TABLE subcuentas (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuenta_id           BIGINT NOT NULL,
    numero_subcuenta    SMALLINT NOT NULL,
    nombre              VARCHAR(100) NULL,
    tipo_division       VARCHAR(15) NOT NULL,
    porcentaje_asignado DECIMAL(7,4) NULL,
    estado              VARCHAR(15) NOT NULL DEFAULT 'PENDIENTE',
    subtotal_snapshot   DECIMAL(12,2) NOT NULL DEFAULT 0,
    creado_en           TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en      TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_subcuenta_numero UNIQUE (cuenta_id, numero_subcuenta),
    CONSTRAINT chk_subcuenta_numero CHECK (numero_subcuenta > 0),
    CONSTRAINT chk_subcuenta_tipo CHECK (
        tipo_division IN ('PERSONAS', 'ITEMS')
    ),
    CONSTRAINT chk_subcuenta_porcentaje CHECK (
        (tipo_division = 'ITEMS' AND porcentaje_asignado IS NULL)
        OR (
            tipo_division = 'PERSONAS'
            AND porcentaje_asignado > 0
            AND porcentaje_asignado <= 100
        )
    ),
    CONSTRAINT chk_subcuenta_estado CHECK (
        estado IN ('PENDIENTE', 'FACTURADA', 'CANCELADA')
    ),
    CONSTRAINT chk_subcuenta_subtotal CHECK (subtotal_snapshot >= 0),
    CONSTRAINT fk_subcuenta_cuenta
        FOREIGN KEY (cuenta_id) REFERENCES cuentas(id)
        ON UPDATE RESTRICT ON DELETE CASCADE
);

CREATE TABLE comandas (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuenta_id           BIGINT NOT NULL,
    numero_ronda        SMALLINT NOT NULL,
    mesero_id           BIGINT NOT NULL,
    estado              VARCHAR(20) NOT NULL DEFAULT 'BORRADOR',
    creada_en           TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    enviada_en          TIMESTAMPTZ(6) NULL,
    finalizada_en       TIMESTAMPTZ(6) NULL,
    notas_generales     VARCHAR(500) NULL,
    CONSTRAINT uq_comanda_ronda UNIQUE (cuenta_id, numero_ronda),
    CONSTRAINT chk_comanda_numero_ronda CHECK (numero_ronda > 0),
    CONSTRAINT chk_comanda_estado CHECK (
        estado IN (
            'BORRADOR', 'RECIBIDA', 'EN_PREPARACION',
            'LISTA', 'ENTREGADA', 'CANCELADA'
        )
    ),
    CONSTRAINT chk_comanda_fechas_estado CHECK (
        (estado = 'BORRADOR'
            AND enviada_en IS NULL
            AND finalizada_en IS NULL)
        OR (estado IN ('RECIBIDA', 'EN_PREPARACION', 'LISTA')
            AND enviada_en IS NOT NULL
            AND finalizada_en IS NULL)
        OR (estado IN ('ENTREGADA', 'CANCELADA')
            AND enviada_en IS NOT NULL
            AND finalizada_en IS NOT NULL)
    ),
    CONSTRAINT fk_comanda_cuenta
        FOREIGN KEY (cuenta_id) REFERENCES cuentas(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_comanda_mesero
        FOREIGN KEY (mesero_id) REFERENCES usuarios(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT
);

CREATE INDEX idx_comandas_cocina
    ON comandas (estado, enviada_en);

-- Cada renglon representa un platillo o un combo. Se guardan snapshots para que
-- cambios futuros de nombre, precio, receta o tiempo no alteren la venta historica.
CREATE TABLE comanda_detalles (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comanda_id                  BIGINT NOT NULL,
    platillo_id                 BIGINT NULL,
    combo_id                    BIGINT NULL,
    receta_version_id           BIGINT NULL,
    nombre_snapshot             VARCHAR(150) NOT NULL,
    cantidad                    SMALLINT NOT NULL,
    precio_unitario_snapshot    DECIMAL(12,2) NOT NULL,
    costo_unitario_snapshot     DECIMAL(14,4) NOT NULL DEFAULT 0,
    tiempo_estimado_minutos     SMALLINT NOT NULL,
    notas_especiales            VARCHAR(500) NULL,
    estado                      VARCHAR(20) NOT NULL DEFAULT 'BORRADOR',
    recibido_en                 TIMESTAMPTZ(6) NULL,
    preparacion_iniciada_en     TIMESTAMPTZ(6) NULL,
    listo_en                    TIMESTAMPTZ(6) NULL,
    entregado_en                TIMESTAMPTZ(6) NULL,
    actualizado_por_id          BIGINT NULL,
    actualizado_en              TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_comanda_detalle_producto CHECK (
        (platillo_id IS NOT NULL AND combo_id IS NULL)
        OR (platillo_id IS NULL AND combo_id IS NOT NULL)
    ),
    CONSTRAINT chk_comanda_detalle_receta CHECK (
        (platillo_id IS NOT NULL
            AND combo_id IS NULL
            AND receta_version_id IS NOT NULL)
        OR (platillo_id IS NULL
            AND combo_id IS NOT NULL
            AND receta_version_id IS NULL)
    ),
    CONSTRAINT chk_comanda_detalle_valores CHECK (
        cantidad > 0
        AND precio_unitario_snapshot >= 0
        AND costo_unitario_snapshot >= 0
        AND tiempo_estimado_minutos > 0
    ),
    CONSTRAINT chk_comanda_detalle_estado CHECK (
        estado IN (
            'BORRADOR', 'RECIBIDO', 'EN_PREPARACION', 'LISTO',
            'ENTREGADO', 'NO_DISPONIBLE', 'CANCELADO'
        )
    ),
    CONSTRAINT chk_comanda_detalle_fechas CHECK (
        (estado = 'BORRADOR'
            AND recibido_en IS NULL
            AND preparacion_iniciada_en IS NULL
            AND listo_en IS NULL
            AND entregado_en IS NULL)
        OR (estado IN ('RECIBIDO', 'NO_DISPONIBLE', 'CANCELADO')
            AND recibido_en IS NOT NULL)
        OR (estado = 'EN_PREPARACION'
            AND recibido_en IS NOT NULL
            AND preparacion_iniciada_en IS NOT NULL)
        OR (estado = 'LISTO'
            AND recibido_en IS NOT NULL
            AND preparacion_iniciada_en IS NOT NULL
            AND listo_en IS NOT NULL)
        OR (estado = 'ENTREGADO'
            AND recibido_en IS NOT NULL
            AND preparacion_iniciada_en IS NOT NULL
            AND listo_en IS NOT NULL
            AND entregado_en IS NOT NULL)
    ),
    CONSTRAINT fk_comanda_detalle_comanda
        FOREIGN KEY (comanda_id) REFERENCES comandas(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_comanda_detalle_platillo
        FOREIGN KEY (platillo_id) REFERENCES platillos(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_comanda_detalle_combo
        FOREIGN KEY (combo_id) REFERENCES combos(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_comanda_detalle_receta
        FOREIGN KEY (receta_version_id) REFERENCES receta_versiones(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_comanda_detalle_usuario
        FOREIGN KEY (actualizado_por_id) REFERENCES usuarios(id)
        ON UPDATE RESTRICT ON DELETE SET NULL
);

CREATE INDEX idx_comanda_detalles_cocina
    ON comanda_detalles (estado, recibido_en);
CREATE INDEX idx_comanda_detalles_comanda
    ON comanda_detalles (comanda_id, estado);

-- Congela los componentes y versiones de receta de un combo cuando se agrega
-- a una comanda. Asi una edicion posterior del combo o de sus recetas no cambia
-- el costo ni los insumos que se descontaran para esa orden ya capturada.
CREATE TABLE comanda_detalle_combo_recetas (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comanda_detalle_id          BIGINT NOT NULL,
    platillo_id                 BIGINT NOT NULL,
    receta_version_id           BIGINT NOT NULL,
    cantidad_platillo           SMALLINT NOT NULL,
    costo_unitario_snapshot     DECIMAL(14,4) NOT NULL,
    CONSTRAINT uq_comanda_combo_receta
        UNIQUE (comanda_detalle_id, platillo_id),
    CONSTRAINT chk_comanda_combo_receta_valores CHECK (
        cantidad_platillo > 0 AND costo_unitario_snapshot >= 0
    ),
    CONSTRAINT fk_comanda_combo_receta_detalle
        FOREIGN KEY (comanda_detalle_id) REFERENCES comanda_detalles(id)
        ON UPDATE RESTRICT ON DELETE CASCADE,
    CONSTRAINT fk_comanda_combo_receta_platillo
        FOREIGN KEY (platillo_id) REFERENCES platillos(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_comanda_combo_receta_version
        FOREIGN KEY (receta_version_id) REFERENCES receta_versiones(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT
);

CREATE INDEX idx_comanda_combo_receta_version
    ON comanda_detalle_combo_recetas (receta_version_id);

