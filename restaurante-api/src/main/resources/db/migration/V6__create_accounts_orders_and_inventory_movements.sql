-- Registra cancelaciones normales, excepciones autorizadas y faltantes reales
-- detectados por cocina. La accion de inventario queda trazable.
CREATE TABLE cancelaciones_comanda_detalle (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comanda_detalle_id      BIGINT NOT NULL,
    tipo                    VARCHAR(30) NOT NULL,
    motivo                  VARCHAR(500) NOT NULL,
    estado_solicitud        VARCHAR(15) NOT NULL DEFAULT 'PENDIENTE',
    accion_inventario       VARCHAR(25) NOT NULL DEFAULT 'SIN_AJUSTE',
    solicitada_por_id       BIGINT NOT NULL,
    autorizada_por_id       BIGINT NULL,
    solicitada_en           TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resuelta_en             TIMESTAMPTZ(6) NULL,
    CONSTRAINT uq_cancelacion_detalle UNIQUE (comanda_detalle_id),
    CONSTRAINT chk_cancelacion_tipo CHECK (
        tipo IN ('CLIENTE', 'ERROR_MESERO', 'NO_DISPONIBLE_COCINA', 'OTRO')
    ),
    CONSTRAINT chk_cancelacion_estado CHECK (
        estado_solicitud IN ('PENDIENTE', 'APROBADA', 'RECHAZADA')
    ),
    CONSTRAINT chk_cancelacion_inventario CHECK (
        accion_inventario IN ('REINTEGRAR', 'REGISTRAR_MERMA', 'SIN_AJUSTE')
    ),
    CONSTRAINT chk_cancelacion_resolucion CHECK (
        (estado_solicitud = 'PENDIENTE'
            AND autorizada_por_id IS NULL
            AND resuelta_en IS NULL)
        OR (estado_solicitud IN ('APROBADA', 'RECHAZADA')
            AND autorizada_por_id IS NOT NULL
            AND resuelta_en IS NOT NULL
            AND resuelta_en >= solicitada_en)
    ),
    CONSTRAINT chk_cancelacion_accion_estado CHECK (
        estado_solicitud = 'APROBADA'
        OR accion_inventario = 'SIN_AJUSTE'
    ),
    CONSTRAINT fk_cancelacion_detalle
        FOREIGN KEY (comanda_detalle_id) REFERENCES comanda_detalles(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_cancelacion_solicitante
        FOREIGN KEY (solicitada_por_id) REFERENCES usuarios(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_cancelacion_autorizador
        FOREIGN KEY (autorizada_por_id) REFERENCES usuarios(id)
        ON UPDATE RESTRICT ON DELETE SET NULL
);

