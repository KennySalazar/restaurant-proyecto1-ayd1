-- Cuentas, comandas, cocina, divisiones e inventario transaccional.
SET search_path TO restaurante, public;
SET TIME ZONE 'UTC';

CREATE TABLE cuentas (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurante_id          BIGINT NOT NULL,
    mesa_id                 BIGINT NOT NULL,
    mesero_id               BIGINT NOT NULL,
    cliente_id              BIGINT NULL,
    reserva_id              BIGINT NULL,
    lista_espera_id         BIGINT NULL,
    numero_cuenta           VARCHAR(30) NOT NULL,
    cantidad_personas       SMALLINT NOT NULL DEFAULT 1,
    estado                  VARCHAR(25) NOT NULL DEFAULT 'ABIERTA',
    abierta_en              TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    solicitada_cobro_en     TIMESTAMPTZ(6) NULL,
    cerrada_en              TIMESTAMPTZ(6) NULL,
    observaciones           VARCHAR(500) NULL,
    creado_en               TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en          TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_cuenta_numero UNIQUE (restaurante_id, numero_cuenta),
    CONSTRAINT uq_cuenta_reserva UNIQUE (reserva_id),
    CONSTRAINT uq_cuenta_lista_espera UNIQUE (lista_espera_id),
    CONSTRAINT chk_cuenta_personas CHECK (cantidad_personas > 0),
    CONSTRAINT chk_cuenta_origen_cliente CHECK (
        num_nonnulls(reserva_id, lista_espera_id) <= 1
    ),
    CONSTRAINT chk_cuenta_estado CHECK (
        estado IN (
            'ABIERTA', 'LISTA_COBRO', 'PARCIALMENTE_PAGADA',
            'CERRADA', 'CANCELADA', 'FUSIONADA'
        )
    ),
    CONSTRAINT chk_cuenta_fechas_estado CHECK (
        (estado IN ('ABIERTA', 'LISTA_COBRO', 'PARCIALMENTE_PAGADA')
            AND cerrada_en IS NULL)
        OR (estado IN ('CERRADA', 'CANCELADA', 'FUSIONADA')
            AND cerrada_en IS NOT NULL)
    ),
    CONSTRAINT fk_cuenta_restaurante
        FOREIGN KEY (restaurante_id) REFERENCES restaurantes(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_cuenta_mesa
        FOREIGN KEY (mesa_id) REFERENCES mesas(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_cuenta_mesero
        FOREIGN KEY (mesero_id) REFERENCES usuarios(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_cuenta_cliente
        FOREIGN KEY (cliente_id) REFERENCES clientes(id)
        ON UPDATE RESTRICT ON DELETE SET NULL,
    CONSTRAINT fk_cuenta_reserva
        FOREIGN KEY (reserva_id) REFERENCES reservas(id)
        ON UPDATE RESTRICT ON DELETE SET NULL,
    CONSTRAINT fk_cuenta_lista_espera
        FOREIGN KEY (lista_espera_id) REFERENCES lista_espera(id)
        ON UPDATE RESTRICT ON DELETE SET NULL
);

CREATE UNIQUE INDEX uq_cuenta_activa_mesa
    ON cuentas (mesa_id)
    WHERE estado IN ('ABIERTA', 'LISTA_COBRO', 'PARCIALMENTE_PAGADA');

CREATE INDEX idx_cuentas_mesero_estado
    ON cuentas (mesero_id, estado, abierta_en);
CREATE INDEX idx_cuentas_listas_cobro
    ON cuentas (restaurante_id, estado, solicitada_cobro_en);

-- Relaciona una cuenta con todas las mesas que mantiene ocupadas. La columna
-- cuentas.mesa_id conserva la mesa principal para compatibilidad con la API,
-- mientras esta tabla permite mantener mesas anexas durante una fusion.
CREATE TABLE cuenta_mesas (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuenta_id           BIGINT NOT NULL,
    mesa_id             BIGINT NOT NULL,
    es_principal        BOOLEAN NOT NULL DEFAULT FALSE,
    origen_cuenta_id    BIGINT NULL,
    activa              BOOLEAN NOT NULL DEFAULT TRUE,
    vinculada_en        TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    desvinculada_en     TIMESTAMPTZ(6) NULL,
    CONSTRAINT uq_cuenta_mesa UNIQUE (cuenta_id, mesa_id),
    CONSTRAINT chk_cuenta_mesa_vigencia CHECK (
        (activa = TRUE AND desvinculada_en IS NULL)
        OR (activa = FALSE AND desvinculada_en IS NOT NULL)
    ),
    CONSTRAINT fk_cuenta_mesa_cuenta
        FOREIGN KEY (cuenta_id) REFERENCES cuentas(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_cuenta_mesa_mesa
        FOREIGN KEY (mesa_id) REFERENCES mesas(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_cuenta_mesa_origen
        FOREIGN KEY (origen_cuenta_id) REFERENCES cuentas(id)
        ON UPDATE RESTRICT ON DELETE SET NULL
);

CREATE UNIQUE INDEX uq_cuenta_mesa_activa
    ON cuenta_mesas (mesa_id)
    WHERE activa = TRUE;

CREATE INDEX idx_cuenta_mesas_cuenta_activas
    ON cuenta_mesas (cuenta_id, activa, es_principal);

