CREATE TABLE entradas_inventario (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurante_id      BIGINT NOT NULL,
    numero_documento    VARCHAR(40) NOT NULL,
    fecha_recepcion     TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    proveedor_nombre    VARCHAR(150) NULL,
    referencia_compra   VARCHAR(100) NULL,
    observaciones       VARCHAR(500) NULL,
    recibida_por_id     BIGINT NOT NULL,
    creado_en           TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_entrada_documento UNIQUE (restaurante_id, numero_documento),
    CONSTRAINT fk_entrada_restaurante
        FOREIGN KEY (restaurante_id) REFERENCES restaurantes(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_entrada_usuario
        FOREIGN KEY (recibida_por_id) REFERENCES usuarios(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT
);

CREATE TABLE entrada_inventario_detalles (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entrada_id          BIGINT NOT NULL,
    insumo_id           BIGINT NOT NULL,
    cantidad            DECIMAL(18,4) NOT NULL,
    costo_unitario      DECIMAL(14,4) NOT NULL,
    costo_total         DECIMAL(18,4) GENERATED ALWAYS AS
                        (ROUND(cantidad * costo_unitario, 4)) STORED,
    lote                VARCHAR(80) NULL,
    fecha_vencimiento   DATE NULL,
    CONSTRAINT uq_entrada_detalle_insumo_lote
        UNIQUE (entrada_id, insumo_id, lote),
    CONSTRAINT chk_entrada_detalle_valores CHECK (
        cantidad > 0 AND costo_unitario >= 0
    ),
    CONSTRAINT fk_entrada_detalle_entrada
        FOREIGN KEY (entrada_id) REFERENCES entradas_inventario(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_entrada_detalle_insumo
        FOREIGN KEY (insumo_id) REFERENCES insumos(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT
);

CREATE TABLE mermas (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurante_id      BIGINT NOT NULL,
    numero_documento    VARCHAR(40) NOT NULL,
    tipo_motivo         VARCHAR(20) NOT NULL,
    motivo_general      VARCHAR(500) NOT NULL,
    registrada_por_id   BIGINT NOT NULL,
    registrada_en       TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_merma_documento UNIQUE (restaurante_id, numero_documento),
    CONSTRAINT chk_merma_motivo CHECK (
        tipo_motivo IN ('VENCIMIENTO', 'DANO', 'ERROR_MANEJO', 'OTRO')
    ),
    CONSTRAINT fk_merma_restaurante
        FOREIGN KEY (restaurante_id) REFERENCES restaurantes(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_merma_usuario
        FOREIGN KEY (registrada_por_id) REFERENCES usuarios(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT
);

CREATE TABLE merma_detalles (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    merma_id                BIGINT NOT NULL,
    insumo_id               BIGINT NOT NULL,
    cantidad                DECIMAL(18,4) NOT NULL,
    costo_unitario_snapshot DECIMAL(14,4) NOT NULL,
    costo_total             DECIMAL(18,4) GENERATED ALWAYS AS
                            (ROUND(cantidad * costo_unitario_snapshot, 4)) STORED,
    lote                    VARCHAR(80) NULL,
    observacion             VARCHAR(255) NULL,
    CONSTRAINT uq_merma_detalle_insumo_lote
        UNIQUE (merma_id, insumo_id, lote),
    CONSTRAINT chk_merma_detalle_valores CHECK (
        cantidad > 0 AND costo_unitario_snapshot >= 0
    ),
    CONSTRAINT fk_merma_detalle_merma
        FOREIGN KEY (merma_id) REFERENCES mermas(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_merma_detalle_insumo
        FOREIGN KEY (insumo_id) REFERENCES insumos(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT
);

-- Todas las cantidades del kardex se guardan en la unidad de stock del insumo.
CREATE TABLE movimientos_inventario (
    id                              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurante_id                  BIGINT NOT NULL,
    insumo_id                       BIGINT NOT NULL,
    tipo                            VARCHAR(30) NOT NULL,
    cantidad                        DECIMAL(18,4) NOT NULL,
    stock_anterior                  DECIMAL(18,4) NULL,
    stock_resultante                DECIMAL(18,4) NULL,
    costo_unitario_snapshot         DECIMAL(14,4) NULL,
    costo_total_snapshot            DECIMAL(18,4) GENERATED ALWAYS AS
                                    (ROUND(cantidad * costo_unitario_snapshot, 4)) STORED,
    entrada_detalle_id              BIGINT NULL,
    merma_detalle_id                BIGINT NULL,
    comanda_detalle_id              BIGINT NULL,
    cancelacion_comanda_detalle_id  BIGINT NULL,
    motivo                          VARCHAR(500) NOT NULL,
    usuario_responsable_id          BIGINT NOT NULL,
    creado_en                       TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_movimiento_entrada_detalle UNIQUE (entrada_detalle_id),
    CONSTRAINT uq_movimiento_merma_detalle UNIQUE (merma_detalle_id),
    CONSTRAINT chk_movimiento_tipo CHECK (
        tipo IN (
            'ENTRADA_COMPRA', 'SALIDA_VENTA', 'SALIDA_MERMA',
            'AJUSTE_ENTRADA', 'AJUSTE_SALIDA', 'REINTEGRO_CANCELACION'
        )
    ),
    CONSTRAINT chk_movimiento_cantidad CHECK (cantidad > 0),
    CONSTRAINT chk_movimiento_stock CHECK (
        stock_anterior IS NULL OR stock_anterior >= 0
    ),
    CONSTRAINT chk_movimiento_resultante CHECK (
        stock_resultante IS NULL OR stock_resultante >= 0
    ),
    CONSTRAINT chk_movimiento_origen CHECK (
        (
            tipo = 'ENTRADA_COMPRA'
            AND entrada_detalle_id IS NOT NULL
            AND num_nonnulls(
                entrada_detalle_id, merma_detalle_id,
                comanda_detalle_id, cancelacion_comanda_detalle_id
            ) = 1
        )
        OR (
            tipo = 'SALIDA_MERMA'
            AND merma_detalle_id IS NOT NULL
            AND num_nonnulls(
                entrada_detalle_id, merma_detalle_id,
                comanda_detalle_id, cancelacion_comanda_detalle_id
            ) = 1
        )
        OR (
            tipo = 'SALIDA_VENTA'
            AND comanda_detalle_id IS NOT NULL
            AND num_nonnulls(
                entrada_detalle_id, merma_detalle_id,
                comanda_detalle_id, cancelacion_comanda_detalle_id
            ) = 1
        )
        OR (
            tipo = 'REINTEGRO_CANCELACION'
            AND cancelacion_comanda_detalle_id IS NOT NULL
            AND num_nonnulls(
                entrada_detalle_id, merma_detalle_id,
                comanda_detalle_id, cancelacion_comanda_detalle_id
            ) = 1
        )
        OR (
            tipo IN ('AJUSTE_ENTRADA', 'AJUSTE_SALIDA')
            AND num_nonnulls(
                entrada_detalle_id, merma_detalle_id,
                comanda_detalle_id, cancelacion_comanda_detalle_id
            ) = 0
        )
    ),
    CONSTRAINT fk_movimiento_restaurante
        FOREIGN KEY (restaurante_id) REFERENCES restaurantes(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_movimiento_insumo
        FOREIGN KEY (insumo_id) REFERENCES insumos(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_movimiento_entrada_detalle
        FOREIGN KEY (entrada_detalle_id) REFERENCES entrada_inventario_detalles(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_movimiento_merma_detalle
        FOREIGN KEY (merma_detalle_id) REFERENCES merma_detalles(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_movimiento_comanda_detalle
        FOREIGN KEY (comanda_detalle_id) REFERENCES comanda_detalles(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_movimiento_cancelacion
        FOREIGN KEY (cancelacion_comanda_detalle_id)
        REFERENCES cancelaciones_comanda_detalle(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_movimiento_usuario
        FOREIGN KEY (usuario_responsable_id) REFERENCES usuarios(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT
);

