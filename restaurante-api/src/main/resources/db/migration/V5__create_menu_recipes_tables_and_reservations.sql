CREATE TABLE reservas (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurante_id          BIGINT NOT NULL,
    mesa_id                 BIGINT NOT NULL,
    cliente_id              BIGINT NULL,
    codigo_reserva          VARCHAR(30) NOT NULL,
    nombre_cliente          VARCHAR(150) NOT NULL,
    telefono_cliente        VARCHAR(25) NOT NULL,
    cantidad_personas       SMALLINT NOT NULL,
    fecha_hora_inicio       TIMESTAMPTZ(6) NOT NULL,
    fecha_hora_fin          TIMESTAMPTZ(6) NOT NULL,
    estado                  VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    notas                   VARCHAR(500) NULL,
    creada_por_id           BIGINT NULL,
    confirmada_en           TIMESTAMPTZ(6) NULL,
    llegada_en              TIMESTAMPTZ(6) NULL,
    cancelada_en            TIMESTAMPTZ(6) NULL,
    motivo_cancelacion      VARCHAR(500) NULL,
    creado_en               TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en          TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_reserva_codigo UNIQUE (restaurante_id, codigo_reserva),
    CONSTRAINT chk_reserva_personas CHECK (cantidad_personas > 0),
    CONSTRAINT chk_reserva_fechas CHECK (fecha_hora_fin > fecha_hora_inicio),
    CONSTRAINT chk_reserva_estado CHECK (
        estado IN (
            'PENDIENTE', 'CONFIRMADA', 'CLIENTE_PRESENTE',
            'ATENDIDA', 'CANCELADA', 'NO_ASISTIO'
        )
    ),
    CONSTRAINT fk_reserva_restaurante
        FOREIGN KEY (restaurante_id) REFERENCES restaurantes(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_reserva_mesa
        FOREIGN KEY (mesa_id) REFERENCES mesas(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_reserva_cliente
        FOREIGN KEY (cliente_id) REFERENCES clientes(id)
        ON UPDATE RESTRICT ON DELETE SET NULL,
    CONSTRAINT fk_reserva_creada_por
        FOREIGN KEY (creada_por_id) REFERENCES usuarios(id)
        ON UPDATE RESTRICT ON DELETE SET NULL
);

CREATE INDEX idx_reservas_mesa_horario
    ON reservas (mesa_id, fecha_hora_inicio, fecha_hora_fin, estado);
CREATE INDEX idx_reservas_proximas
    ON reservas (restaurante_id, estado, fecha_hora_inicio);
CREATE INDEX idx_reservas_telefono
    ON reservas (restaurante_id, telefono_cliente, fecha_hora_inicio);

ALTER TABLE reservas
    ADD CONSTRAINT ex_reservas_mesa_horario
    EXCLUDE USING gist (
        mesa_id WITH =,
        tstzrange(fecha_hora_inicio, fecha_hora_fin, '[)') WITH &&
    )
    WHERE (
        estado IN ('PENDIENTE', 'CONFIRMADA', 'CLIENTE_PRESENTE')
    );

