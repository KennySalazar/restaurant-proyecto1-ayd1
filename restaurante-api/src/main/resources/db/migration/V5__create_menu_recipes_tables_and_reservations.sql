CREATE TABLE categorias_platillo (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurante_id  BIGINT NOT NULL,
    codigo          VARCHAR(30) NOT NULL,
    nombre          VARCHAR(80) NOT NULL,
    descripcion     VARCHAR(255) NULL,
    orden_visual    SMALLINT NOT NULL DEFAULT 0,
    activo          BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_categoria_platillo_codigo
        UNIQUE (restaurante_id, codigo),
    CONSTRAINT uq_categoria_platillo_nombre
        UNIQUE (restaurante_id, nombre),
    CONSTRAINT fk_categoria_platillo_restaurante
        FOREIGN KEY (restaurante_id) REFERENCES restaurantes(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT
);

CREATE TABLE platillos (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurante_id              BIGINT NOT NULL,
    categoria_platillo_id       BIGINT NOT NULL,
    codigo                      VARCHAR(30) NOT NULL,
    nombre                      VARCHAR(120) NOT NULL,
    descripcion                 VARCHAR(500) NULL,
    precio_venta                DECIMAL(12,2) NOT NULL,
    imagen_url                  VARCHAR(500) NULL,
    tiempo_preparacion_minutos  SMALLINT NOT NULL,
    disponible_manual           BOOLEAN NOT NULL DEFAULT TRUE,
    activo                      BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en                   TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en              TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_platillo_codigo UNIQUE (restaurante_id, codigo),
    CONSTRAINT uq_platillo_nombre UNIQUE (restaurante_id, nombre),
    CONSTRAINT chk_platillo_precio_tiempo CHECK (
        precio_venta >= 0 AND tiempo_preparacion_minutos > 0
    ),
    CONSTRAINT fk_platillo_restaurante
        FOREIGN KEY (restaurante_id) REFERENCES restaurantes(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_platillo_categoria
        FOREIGN KEY (categoria_platillo_id) REFERENCES categorias_platillo(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT
);

CREATE INDEX idx_platillos_menu
    ON platillos (restaurante_id, categoria_platillo_id, activo, disponible_manual);


CREATE TABLE receta_versiones (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    platillo_id             BIGINT NOT NULL,
    numero_version          INTEGER NOT NULL,
    estado                  VARCHAR(15) NOT NULL DEFAULT 'BORRADOR',
    motivo_cambio           VARCHAR(500) NULL,
    vigente_desde           TIMESTAMPTZ(6) NULL,
    vigente_hasta           TIMESTAMPTZ(6) NULL,
    creado_por_id           BIGINT NULL,
    creado_en               TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_receta_version UNIQUE (platillo_id, numero_version),
    CONSTRAINT chk_receta_numero_version CHECK (numero_version > 0),
    CONSTRAINT chk_receta_version_estado CHECK (
        estado IN ('BORRADOR', 'VIGENTE', 'HISTORICA')
    ),
    CONSTRAINT chk_receta_version_fechas CHECK (
        (estado = 'BORRADOR'
            AND vigente_desde IS NULL
            AND vigente_hasta IS NULL)
        OR (estado = 'VIGENTE'
            AND vigente_desde IS NOT NULL
            AND vigente_hasta IS NULL)
        OR (estado = 'HISTORICA'
            AND vigente_desde IS NOT NULL
            AND vigente_hasta IS NOT NULL
            AND vigente_hasta > vigente_desde)
    ),
    CONSTRAINT fk_receta_version_platillo
        FOREIGN KEY (platillo_id) REFERENCES platillos(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_receta_version_usuario
        FOREIGN KEY (creado_por_id) REFERENCES usuarios(id)
        ON UPDATE RESTRICT ON DELETE SET NULL
);

CREATE UNIQUE INDEX uq_receta_platillo_vigente
    ON receta_versiones (platillo_id)
    WHERE estado = 'VIGENTE';

CREATE TABLE receta_detalles (
